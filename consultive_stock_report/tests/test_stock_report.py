    def _process_move(self, move, qty):
        """Complete a move the Odoo 19 way (quantity -> picked -> done)."""
        move._action_confirm()
        move._action_assign()
        move.quantity = qty
        move.picked = True
        move._action_done()

    def test_tie_out_with_quant(self):
        """Final balance must equal the stock quant quantity."""
        move = self.Move.create({
            'product_id': self.product.id,
            'product_uom_qty': 25,
            'location_id': self.supplier_loc.id,
            'location_dest_id': self.stock_loc.id,
            'company_id': self.company.id,
        })
        self._process_move(move, 25)
        move2 = self.Move.create({
            'product_id': self.product.id,
            'product_uom_qty': 10,
            'location_id': self.stock_loc.id,
            'location_dest_id': self.customer_loc.id,
            'company_id': self.company.id,
        })
        self._process_move(move2, 10)

        today = fields.Date.context_today(self.env.user)
        lines = self._run_wizard(today, today)
        total = self._totals(lines)
        quant_qty = sum(
            self.env['stock.quant'].search([
                ('product_id', '=', self.product.id),
                ('location_id', 'child_of', self.stock_loc.id),
                ('company_id', '=', self.company.id),
            ]).mapped('quantity'))
        self.assertEqual(total.balance, quant_qty)

