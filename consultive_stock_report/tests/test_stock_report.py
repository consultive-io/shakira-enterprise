    def test_adjustment_and_scrap(self):
        self._create_done_move(
            self.supplier_loc, self.stock_loc, 100, days_ago=1)
        # inventory shrinkage: internal -> inventory adjustment location
        self._create_done_move(
            self.stock_loc, self.adjust_loc, 7, days_ago=0)
        # move to the scrap *location* without a scrap record: still an
        # adjustment by location usage (only scrap_id marks real scraps)
        self._create_done_move(
            self.stock_loc, self.scraps_loc, 3, days_ago=0)
        lines = self._run_wizard(
            date.today() - timedelta(days=1), date.today())
        total = self._totals(lines)
        self.assertEqual(total.adjustments, -10)
        self.assertEqual(total.scraps, 0)
        self.assertEqual(total.balance, 90)

        # now with scrap_id set -> counted as scrap
        self.env['stock.report.line']._user_lines().unlink()
        scrap = self.env['stock.scrap'].create({
            'product_id': self.product.id,
            'product_uom_id': self.product.uom_id.id,
            'scrap_qty': 2,
            'location_id': self.stock_loc.id,
            'scrap_location_id': self.scraps_loc.id,
            'company_id': self.company.id,
        })
        self._create_done_move(
            self.stock_loc, self.scraps_loc, 2, days_ago=0,
            scrap_id=scrap.id)
        lines = self._run_wizard(
            date.today() - timedelta(days=1), date.today())
        total = self._totals(lines)
        self.assertEqual(total.scraps, -2)
        self.assertEqual(total.adjustments, -10)

    def test_manufacture_and_unbuild(self):
        # a real unbuild record for the unbuild_id anchor
        component = self.env['product.product'].create({
            'name': 'Test Component',
            'is_storable': True,
        })
        bom = self.env['mrp.bom'].create({
            'product_tmpl_id': self.product.product_tmpl_id.id,
            'product_qty': 1,
        })
        self.env['mrp.bom.line'].create({
            'bom_id': bom.id,
            'product_id': component.id,
            'product_qty': 1,
        })
        unbuild = self.env['mrp.unbuild'].create({
            'name': 'Test Unbuild',
            'product_id': self.product.id,
            'bom_id': bom.id,
            'product_qty': 4,
            'product_uom_id': self.product.uom_id.id,
            'company_id': self.company.id,
        })
        self._create_done_move(
            self.production_loc, self.stock_loc, 10, days_ago=1)  # MO output
        self._create_done_move(
            self.stock_loc, self.production_loc, 40, days_ago=1)  # raw consumption
        self._create_done_move(
            self.stock_loc, self.production_loc, 4, days_ago=0,
            unbuild_id=unbuild.id)  # unbuild finished goods out
        self._create_done_move(
            self.production_loc, self.stock_loc, 4, days_ago=0,
            unbuild_id=unbuild.id)  # unbuild components back in
        lines = self._run_wizard(
            date.today() - timedelta(days=1), date.today())
        total = self._totals(lines)
        self.assertEqual(total.manufacture_in, 10)
        self.assertEqual(total.unbuild, -4)
        self.assertEqual(total.mo_component, -40)
        self.assertEqual(total.mo_component_return, 4)
        self.assertEqual(total.balance, 10 - 4 - 40 + 4)

