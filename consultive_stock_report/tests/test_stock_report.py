    def setUp(self):
        super().setUp()
        self.warehouse = self.env.ref('stock.warehouse0')
        self.company = self.warehouse.company_id
        self.supplier_loc = self.env.ref('stock.stock_location_suppliers')
        self.customer_loc = self.env.ref('stock.stock_location_customers')
        self.stock_loc = self.warehouse.lot_stock_id
        self.product = self.env['product.product'].create({
            'name': 'Test Storable',
            'is_storable': True,
        })
        self.production_loc = self.product.property_stock_production

        def _get_or_create_inventory_loc(name):
            loc = self.env['stock.location'].search([
                ('company_id', '=', self.company.id),
                ('usage', '=', 'inventory'),
                ('name', '=', name),
            ], limit=1)
            if not loc:
                loc = self.env['stock.location'].create({
                    'name': name,
                    'usage': 'inventory',
                    'company_id': self.company.id,
                })
            return loc

        self.adjust_loc = _get_or_create_inventory_loc('Inventory adjustment')
        self.scraps_loc = _get_or_create_inventory_loc('Scrap')
        self.Move = self.env['stock.move']

