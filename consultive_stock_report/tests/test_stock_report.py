    def _summary_for(self, warehouse):
        data = self.env['stock.report.line']._build_summary()
        return next(w for w in data if w['id'] == warehouse.id)['days']

    def test_sheet_example_via_summary_and_xlsx(self):
        """Sheet row: 100 + 3 + 4 - 4 - 2 = 101, next day carries 101."""
        today = date.today()
        self._create_done_move(
            self.supplier_loc, self.stock_loc, 100, days_ago=10)
        self._create_done_move(self.supplier_loc, self.stock_loc, 3)
        self._create_done_move(self.production_loc, self.stock_loc, 4)
        self._create_done_move(self.stock_loc, self.production_loc, 4)
        self._create_done_move(self.stock_loc, self.customer_loc, 2)
        wizard = self.env['stock.report.wizard'].create({
            'date_from': today,
            'date_to': today + timedelta(days=1),
            'product_ids': [(6, 0, [self.product.id])],
            'warehouse_ids': [(6, 0, [self.warehouse.id])],
        })
        wizard._generate_lines()
        days = self._summary_for(self.warehouse)
        self.assertEqual(len(days), 2)
        d1, d2 = days
        self.assertEqual(
            (d1['opening_balance'], d1['net_purchase'], d1['net_manufacture'],
             d1['net_consumption'], d1['net_sales'], d1['scraps_shown'],
             d1['other_transfers'], d1['balance']),
            (100, 3, 4, 4, 2, 0, 0, 101))
        self.assertEqual(d2['opening_balance'], 101)
        self.assertEqual(d2['balance'], 101)

        from ..report.stock_report_xlsx import build_summary_workbook
        data = build_summary_workbook(
            wizard, self.env['stock.report.line']._user_lines())
        try:
            import openpyxl
        except ImportError:  # pragma: no cover
            self.assertTrue(data[:2] == b'PK')
            return
        sheet = openpyxl.load_workbook(io.BytesIO(data)).active
        rows = [r for r in sheet.iter_rows(values_only=True)
                if r and r[0] == 1]
        self.assertEqual(rows[0][2:], (100, 3, 4, 4, 2, 0, 0, 101))

