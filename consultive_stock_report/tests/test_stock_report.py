    def _onchange(self, values, changed):
        """Call the server onchange like the web client does."""
        spec = {f: {} for f in (
            'date_from', 'date_to', 'bom_ids', 'product_ids', 'categ_ids',
            'warehouse_ids')}
        return self.env['stock.report.wizard'].onchange(
            values, [changed], spec)['value']

    def test_priority_onchanges_and_category_product_flow(self):
        categ = self.env['product.category'].create({'name': 'Onchange categ'})
        sub = self.env['product.category'].create({
            'name': 'Sub categ', 'parent_id': categ.id})
        other_categ = self.env['product.category'].create({'name': 'Other'})
        product = self.env['product.product'].create({
            'name': 'Onchange product', 'is_storable': True,
            'categ_id': sub.id})
        foreign = self.env['product.product'].create({
            'name': 'Foreign product', 'is_storable': True,
            'categ_id': other_categ.id})
        base = {'date_from': str(date.today()), 'date_to': str(date.today())}
        # category first, then a product of it: the category stays
        value = self._onchange({
            **base,
            'categ_ids': [(6, 0, [categ.id])],
            'product_ids': [(6, 0, [product.id])],
        }, 'product_ids')
        self.assertNotIn('categ_ids', value)
        # changing categories drops products that fall outside of them
        value = self._onchange({
            **base,
            'categ_ids': [(6, 0, [categ.id])],
            'product_ids': [(6, 0, [product.id, foreign.id])],
        }, 'categ_ids')
        commands = value['product_ids']
        self.assertIn(
            foreign.id, [c[1] for c in commands if c[0] == 3],
            'product outside the categories must be dropped')
        self.assertNotIn(
            product.id, [c[1] for c in commands if c[0] == 3])
        # categories only: every product of them (incl. sub-categories)
        wizard = self.env['stock.report.wizard'].create({
            'date_from': date.today(), 'date_to': date.today(),
            'categ_ids': [(6, 0, [categ.id])]})
        self.assertEqual(wizard._get_scoped_products(), product)
        # products chosen directly: only those, category not considered
        wizard.product_ids = foreign
        wizard.categ_ids = categ
        self.assertEqual(wizard._get_scoped_products(), foreign)
        # BOM selected: product and category are emptied
        bom = self.env['mrp.bom'].create({
            'product_tmpl_id': product.product_tmpl_id.id,
            'product_qty': 1})
        value = self._onchange({
            **base,
            'bom_ids': [(6, 0, [bom.id])],
            'product_ids': [(6, 0, [product.id])],
            'categ_ids': [(6, 0, [categ.id])],
        }, 'bom_ids')
        for field in ('product_ids', 'categ_ids'):
            self.assertFalse(
                [c for c in value[field] if c[0] in (4, 6)],
                f'{field} must be emptied once a BOM is selected')
