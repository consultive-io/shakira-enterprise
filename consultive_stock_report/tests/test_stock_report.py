    def test_timezone_day_boundary(self):
        """20:00 UTC yesterday is 02:00 *today* in Asia/Dhaka (UTC+6)."""
        self.env.user.tz = 'Asia/Dhaka'
        import pytz
        local_today = datetime.now(pytz.timezone('Asia/Dhaka')).date()
        utc_moment = datetime.combine(
            local_today - timedelta(days=1), datetime.min.time()
        ).replace(hour=20)
        move = self._create_done_move(
            self.supplier_loc, self.stock_loc, 9)
        move.date = utc_moment
        lines = self._run_wizard(local_today, local_today)
        day_rows = lines.filtered(lambda l: l.line_type == 'day')
        self.assertEqual(day_rows.report_date, local_today)
        self.assertEqual(day_rows.purchase, 9)

