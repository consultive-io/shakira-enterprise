    def _create_done_move(self, src, dst, qty, days_ago=0, product=None, **vals):
        move = self.Move.create({
            'product_id': (product or self.product).id,
            'product_uom_qty': qty,
            'location_id': src.id,
            'location_dest_id': dst.id,
            'date': fields.Datetime.now() - timedelta(days=days_ago),
            'company_id': self.company.id,
            'state': 'done',
            **vals,
        })
        # keep the effective date as requested
        if days_ago:
            move.date = fields.Datetime.now() - timedelta(days=days_ago)
        return move

    def _run_wizard(self, date_from, date_to, **vals):
        wizard = self.env['stock.report.wizard'].create({
            'date_from': date_from,
            'date_to': date_to,
            'product_ids': [(6, 0, vals.pop('product_scope', [self.product.id]))],
            **vals,
        })
        wizard._generate_lines()
        return self.env['stock.report.line'].search([
            ('user_id', '=', self.env.uid)])

    def _totals(self, lines, line_type='total'):
        rec = lines.filtered(lambda l: l.line_type == line_type)
        self.assertTrue(
            rec, f'No {line_type} rows were generated by the report')
        return rec[0] if len(rec) == 1 else rec

