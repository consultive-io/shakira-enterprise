    def test_receipt_and_delivery(self):
        # Receipt yesterday, delivery today
        self._create_done_move(
            self.supplier_loc, self.stock_loc, 100, days_ago=1)
        self._create_done_move(
            self.stock_loc, self.customer_loc, 30, days_ago=0)
        lines = self._run_wizard(
            date.today() - timedelta(days=1), date.today())
        total = self._totals(lines)
        self.assertEqual(total.purchase, 100)
        self.assertEqual(total.sales, -30)
        self.assertEqual(total.opening_balance, 0)
        self.assertEqual(total.balance, 70)
        day_rows = lines.filtered(lambda l: l.line_type == 'day')
        self.assertEqual(len(day_rows), 2)

